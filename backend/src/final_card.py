"""Deterministic final KTRU card: catalogue data plus the recorded clarification answers."""

from backend.src.models import KtruPosition
from backend.src.pipeline import position_reference, value_snapshot


def _characteristic(characteristic):
    return {"code": characteristic.code, "name": characteristic.name,
            "required": characteristic.required, "choice": characteristic.choice,
            "choice_type": characteristic.choice_type, "is_numeric": characteristic.is_numeric,
            "units": sorted({value.okei for value in characteristic.values if value.okei is not None}),
            "values": [value_snapshot(value) for value in characteristic.values]}


def _rationale(position: KtruPosition, answers: list[dict]) -> str:
    choices = "; ".join(f"вопрос {answer['question_id']}, вариант {answer['option_id']}" for answer in answers)
    if not choices:
        return "Множество кандидатов сузилось до кода " + position.code + " без уточняющих вопросов."
    return ("Пользователь выбрал " + choices + " и тем самым сузил множество кандидатов до кода "
            + position.code + ".")


def build_final_card(position: KtruPosition, answers: list[dict]) -> dict:
    """Render the full position schema; nothing here is generated by a model."""
    return {**position_reference(position),
            "characteristics": [_characteristic(characteristic)
                                for characteristic in sorted(position.characteristics, key=lambda item: item.code)
                                if characteristic.actual],
            "rationale": _rationale(position, answers),
            "requires_review": True}
